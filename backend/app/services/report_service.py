"""
Baghewala WellTwin AI - Comprehensive Report Generation Service
Assembles digital-twin state, AI forecasting, optimization scenarios,
and operator decision trails into structured printable and downloadable reports.
"""

from datetime import datetime
from typing import Dict, Any
from app.database import query_one, query_all

class ReportService:
    @staticmethod
    def generate_well_report(well_id: str) -> Dict[str, Any]:
        """
        Compiles all technical modules for a well into an executive decision dossier.
        """
        well = query_one("SELECT * FROM wells WHERE well_id = ?", (well_id,))
        if not well:
            return {"error": f"Well {well_id} not found"}

        latest_sensor = query_one(
            "SELECT * FROM sensor_readings WHERE well_id = ? ORDER BY timestamp DESC LIMIT 1",
            (well_id,)
        ) or {}

        latest_css = query_one(
            "SELECT * FROM css_cycles WHERE well_id = ? ORDER BY cycle_number DESC LIMIT 1",
            (well_id,)
        ) or {}

        latest_srp = query_one(
            "SELECT * FROM srp_readings WHERE well_id = ? ORDER BY timestamp DESC LIMIT 1",
            (well_id,)
        ) or {}

        active_alerts = query_all(
            "SELECT * FROM alerts WHERE well_id = ? AND status != 'RESOLVED' ORDER BY timestamp DESC",
            (well_id,)
        )

        recent_decisions = query_all(
            "SELECT * FROM operator_decisions WHERE well_id = ? ORDER BY timestamp DESC LIMIT 3",
            (well_id,)
        )

        now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        report = {
            "report_id": f"DTR-{well_id}-{datetime.now().strftime('%Y%m%d%H%M')}",
            "generated_at": now_str,
            "project_name": "Baghewala WellTwin AI",
            "problem_statement_id": "SIH26120",
            "organization": "Oil India Limited (Heavy Oil Asset)",
            "well_profile": {
                "well_id": well["well_id"],
                "name": well["name"],
                "field": well["field"],
                "formation": well["formation"],
                "depth_m": well["reservoir_depth_m"],
                "api_gravity": well["api_gravity"],
                "asphaltene_pct": well["asphaltene_pct"],
                "current_status": well["current_status"],
                "current_css_cycle": well["current_css_cycle"],
                "srp_surface_unit": well["surface_unit"]
            },
            "current_operating_condition": {
                "oil_production_bpd": latest_sensor.get("oil_production_bpd", 0.0),
                "reservoir_temp_c": latest_sensor.get("reservoir_temp_c", 0.0),
                "reservoir_pressure_bar": latest_sensor.get("reservoir_pressure_bar", 0.0),
                "oil_viscosity_cp": latest_sensor.get("oil_viscosity_cp", 0.0),
                "power_consumption_kw": latest_sensor.get("power_consumption_kw", 0.0),
                "health_score": latest_sensor.get("health_score", 0.0)
            },
            "css_status": {
                "cycle_number": latest_css.get("cycle_number", 0),
                "current_phase": latest_css.get("current_phase", "N/A"),
                "steam_volume_tons": latest_css.get("steam_volume_tons", 0.0),
                "injection_pressure_bar": latest_css.get("injection_pressure_bar", 0.0),
                "soak_days": latest_css.get("soak_days", 0),
                "cum_oil_produced_bbl": latest_css.get("cum_oil_produced_bbl", 0.0),
                "cut_off_temp_c": latest_css.get("cut_off_temp_c", 0.0)
            },
            "srp_status": {
                "stroke_length_in": latest_srp.get("stroke_length_in", 0.0),
                "spm": latest_srp.get("spm", 0.0),
                "vfd_speed_hz": latest_srp.get("vfd_speed_hz", 0.0),
                "peak_load_lbs": latest_srp.get("peak_polished_rod_load_lbs", 0.0),
                "min_load_lbs": latest_srp.get("min_polished_rod_load_lbs", 0.0),
                "pump_fillage_pct": latest_srp.get("pump_fillage_pct", 0.0),
                "card_type": latest_srp.get("card_type", "NORMAL"),
                "status": latest_srp.get("status", "NORMAL")
            },
            "active_alerts": active_alerts,
            "operator_decisions": recent_decisions,
            "safety_disclaimer": "This document is generated by the Baghewala WellTwin AI decision support prototype. All simulated parameters and optimization suggestions require mandatory operational engineering sign-off prior to field implementation."
        }

        return report
